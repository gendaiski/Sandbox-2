import { build } from 'esbuild';
import { readFile, writeFile, mkdir, cp, rm } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
const root = dirname(fileURLToPath(import.meta.url));
const deployment = resolve(root, 'dist');
const raw = JSON.parse(await readFile(resolve(root, 'cases/index.json'), 'utf8'));
const catalog = Array.isArray(raw) ? raw : raw.cases;
const documents = {};
for (const entry of catalog) documents[entry.id] = JSON.parse(await readFile(resolve(root, `cases/${entry.id}.json`), 'utf8'));
await writeFile(resolve(root, 'case-data.ts'), `export const caseCatalog = ${JSON.stringify(catalog)};\nexport const caseDocuments: Record<string, unknown> = ${JSON.stringify(documents)};\n`);
await rm(deployment, {recursive:true, force:true});
await mkdir(resolve(deployment, 'api'), {recursive:true});
await build({entryPoints:[resolve(root,'api.ts')],bundle:true,platform:'node',format:'esm',target:'node22',outfile:resolve(deployment,'api/index.mjs'),legalComments:'inline',minify:false});
await cp(resolve(root,'public'),deployment,{recursive:true});
await cp(resolve(root,'cases'),resolve(deployment,'cases'),{recursive:true});
await cp(resolve(root,'../LICENSE'),resolve(deployment,'LICENSE.txt'));
await cp(resolve(root,'node_modules/zod/LICENSE'),resolve(deployment,'THIRD-PARTY-LICENSES.txt'));
await writeFile(resolve(deployment,'package.json'),JSON.stringify({name:'pr-lens-review-studio',private:true,type:'module'}));
await writeFile(resolve(deployment,'vercel.json'),JSON.stringify({functions:{'api/index.mjs':{maxDuration:60}},rewrites:[{source:'/api/:path*',destination:'/api/index?route=:path*'}],headers:[{source:'/(.*)',headers:[{key:'X-Content-Type-Options',value:'nosniff'},{key:'Referrer-Policy',value:'strict-origin-when-cross-origin'}]}]},null,2));
console.log('Built PR Lens browser workspace in workspace/dist');
